#!/usr/bin/env python3
"""Run the evaluation configured in evaluation.yaml from this machine."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from dotenv import load_dotenv

from evaluation_config import load_evaluation_config, validate_project_endpoint
from evaluation_runtime import run_local_evaluation


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate target-model responses and run the evaluators configured "
            "in evaluation.yaml."
        )
    )
    parser.add_argument(
        "--config",
        default="evaluation.yaml",
        help="Evaluation YAML configuration (default: evaluation.yaml)",
    )
    parser.add_argument(
        "--local",
        action="store_true",
        help="Run locally (the default; retained for an explicit workflow command)",
    )
    return parser.parse_args()


def resolve_project_endpoint() -> str:
    for name in ("FOUNDRY_PROJECT_ENDPOINT", "AZURE_AI_PROJECT_ENDPOINT"):
        if value := os.getenv(name, "").strip():
            return validate_project_endpoint(value)
    raise RuntimeError(
        "Missing local evaluation configuration. Copy .env.example to .env and "
        "set FOUNDRY_PROJECT_ENDPOINT, or use the .env generated by init."
    )


def main() -> int:
    load_dotenv()
    args = parse_args()
    config = load_evaluation_config(Path(args.config))
    result = run_local_evaluation(config, resolve_project_endpoint())
    if result.gate["enforced"] and not result.gate["passed"]:
        print("Evaluation quality gate failed.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
